# 1. Operações Aritméticas
# -------------------------

print("Operações Aritméticas")

a = 10
b = 10

soma = a + b
subtracao = a - b
multiplicacao = a * b
divisao = a / b
divisao_inteira = a // b
resto = a % b
potencia = a ** b

print(f"Soma: {a} + {b} = {soma}")
print(f"Subtracao: {a} - {b} = {subtracao}")
print(f"Multiplicacao: {a} * {b} = {multiplicacao}")
print(f"Divisao: {a} / {b} = {divisao}")
print(f"Divisao inteira: {a} // {b} = {divisao_inteira}")
print(f"Resto: {a} % {b} = {resto}")
print(f"Potencia: {a} ** {b} = {potencia}")

